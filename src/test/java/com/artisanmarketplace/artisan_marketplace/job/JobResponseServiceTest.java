package com.artisanmarketplace.artisan_marketplace.job;

import com.artisanmarketplace.artisan_marketplace.common.exception.ValidationException;
import com.artisanmarketplace.artisan_marketplace.job.dto.JobResponseRequest;
import com.artisanmarketplace.artisan_marketplace.trade.Trade;
import com.artisanmarketplace.artisan_marketplace.trade.TradeName;
import com.artisanmarketplace.artisan_marketplace.user.Role;
import com.artisanmarketplace.artisan_marketplace.user.User;
import com.artisanmarketplace.artisan_marketplace.user.UserRepository;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.util.List;
import java.util.Optional;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class JobResponseServiceTest {

    @Mock
    private JobRepository jobRepository;
    @Mock
    private JobResponseRepository jobResponseRepository;
    @Mock
    private UserRepository userRepository;
    @InjectMocks
    private JobResponseService jobResponseService;

    @Test
    void shouldSubmitProposalSuccessfully() {
        UUID jobId = UUID.randomUUID();
        UUID artisanId = UUID.randomUUID();
        
        User mockClient = mock(User.class);
        User mockArtisan = mock(User.class);
        when(mockArtisan.getId()).thenReturn(artisanId);
        when(mockArtisan.getRole()).thenReturn(Role.ARTISAN);
        when(mockArtisan.getFullName()).thenReturn("Bob the Builder");

        Job job = new Job(mockClient, new Trade(TradeName.PLUMBER), "Fix sink", "desc", 0.0, 0.0, "loc", JobOrigin.OPEN_POST, 500.0);
        
        JobResponseRequest request = new JobResponseRequest();
        request.setMessage("I can do this tomorrow");
        request.setProposedRate(450.0);

        when(jobRepository.findById(jobId)).thenReturn(Optional.of(job));
        when(userRepository.findById(artisanId)).thenReturn(Optional.of(mockArtisan));
        when(jobResponseRepository.existsByJobIdAndArtisanId(jobId, artisanId)).thenReturn(false);
        when(jobResponseRepository.save(any(JobResponse.class))).thenAnswer(inv -> inv.getArgument(0));

        var result = jobResponseService.submitProposal(jobId, artisanId, request);

        assertThat(result.message()).isEqualTo("I can do this tomorrow");
        assertThat(result.proposedRate()).isEqualTo(450.0);
        assertThat(result.status()).isEqualTo(JobResponseStatus.PENDING);
        assertThat(result.artisanName()).isEqualTo("Bob the Builder");
    }

    @Test
    void shouldRejectDuplicateProposalFromSameArtisan() {
        UUID jobId = UUID.randomUUID();
        UUID artisanId = UUID.randomUUID();
        
        Job job = new Job(mock(User.class), new Trade(TradeName.PLUMBER), "title", "desc", 0.0, 0.0, "loc", JobOrigin.OPEN_POST, 100.0);
        User mockArtisan = mock(User.class);
        when(mockArtisan.getRole()).thenReturn(Role.ARTISAN);

        when(jobRepository.findById(jobId)).thenReturn(Optional.of(job));
        when(userRepository.findById(artisanId)).thenReturn(Optional.of(mockArtisan));
        when(jobResponseRepository.existsByJobIdAndArtisanId(jobId, artisanId)).thenReturn(true);

        assertThatThrownBy(() -> jobResponseService.submitProposal(jobId, artisanId, new JobResponseRequest()))
                .isInstanceOf(ValidationException.class)
                .hasMessageContaining("already submitted");
    }

    @Test
    void shouldAcceptProposalAndRejectOthers() {
        UUID jobId = UUID.randomUUID();
        UUID proposalId = UUID.randomUUID();
        UUID clientId = UUID.randomUUID();
        
        // Setup Job
        User mockClient = mock(User.class);
        when(mockClient.getId()).thenReturn(clientId);
        Job job = new Job(mockClient, new Trade(TradeName.PLUMBER), "title", "desc", 0.0, 0.0, "loc", JobOrigin.OPEN_POST, 100.0);


    // Set job ID via reflection (it's @GeneratedValue so it's null in unit tests)
    try {
        var jobIdField = Job.class.getDeclaredField("id");
        jobIdField.setAccessible(true);
        jobIdField.set(job, jobId);
    } catch (Exception e) { throw new RuntimeException(e); }

        // Setup Proposals
        User mockArtisan1 = mock(User.class);
        JobResponse proposal1 = new JobResponse(job, mockArtisan1, "msg", 100.0);
        // Use reflection to set the ID for the proposal since it's generated by JPA
        try {
            var field = JobResponse.class.getDeclaredField("id");
            field.setAccessible(true);
            field.set(proposal1, proposalId);
        } catch (Exception e) { throw new RuntimeException(e); }

        JobResponse proposal2 = new JobResponse(job, mock(User.class), "msg2", 200.0);
        try {
            var field = JobResponse.class.getDeclaredField("id");
            field.setAccessible(true);
            field.set(proposal2, UUID.randomUUID());
        } catch (Exception e) { throw new RuntimeException(e); }

        when(jobRepository.findById(jobId)).thenReturn(Optional.of(job));
        when(jobResponseRepository.findById(proposalId)).thenReturn(Optional.of(proposal1));
        when(jobResponseRepository.findByJobId(jobId)).thenReturn(List.of(proposal1, proposal2));

        // Execute
        jobResponseService.acceptProposal(jobId, proposalId, clientId);

        // Verify
        assertThat(proposal1.getStatus()).isEqualTo(JobResponseStatus.ACCEPTED);
        assertThat(proposal2.getStatus()).isEqualTo(JobResponseStatus.REJECTED);
        assertThat(job.getStatus()).isEqualTo(JobStatus.REQUESTED);
        assertThat(job.getAssignedArtisan()).isEqualTo(mockArtisan1);
        
        verify(jobRepository).save(job);
        verify(jobResponseRepository, times(2)).save(any(JobResponse.class));
    }
}